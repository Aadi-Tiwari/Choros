import assert from "node:assert/strict";
import { mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ticketSnapshot, ticketFindings } from "../lib/ticket-checks.mjs";
const dir = await mkdtemp(join(tmpdir(), "choros-ticket-checks-"));
const file = join(dir, "data.json");
const order = (id, seats, extra = {}) => ({id,name:id,seats,cancelled:false,promo:null,...extra});
await writeFile(file, JSON.stringify({orders:[order("a",["A1","A2"],{promo:"EARLYBIRD"}),order("b",["B1"])]}));
assert.equal((await ticketSnapshot(file)).sold,3);
assert.equal((await ticketFindings(file,[])).length,0);
const orders = Array.from({length:11},(_,i)=>order(String(i),["A1","A2"],{promo:"EARLYBIRD"}));
await writeFile(file,JSON.stringify({orders}));
const bad = await ticketFindings(file,[]);
assert.deepEqual(new Set(bad.map((f)=>f.evidence.rule)),new Set(["oversell","double_seat","promo_reuse"]));
assert.ok(bad.every((f)=>f.status==='confirmed'));
orders.forEach((o)=>o.cancelled=true);
await writeFile(file,JSON.stringify({orders}));
const cancelled = await ticketFindings(file,[]);
assert.equal((await ticketSnapshot(file)).sold,0);
assert.deepEqual(cancelled.map((f)=>f.evidence.rule),["promo_reuse"],"Cancellation does not erase a promo redemption");
console.log("PASS independent ledger: healthy control, oversell, duplicate owners, promo reuse and cancellation");
